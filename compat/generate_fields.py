#!/usr/bin/env python3
"""Import declarative schemas, including codec fields, from pinned libtiff.
No parser or codec implementation is imported. Every table row is accounted for;
only explicitly ignored fields and pseudo tags (not on-file tags) are omitted.
"""
import argparse
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[1]
source = root / '.tools/tiff-4.7.1/libtiff'
kind = {'UINT8': ('TIFF_BYTE', 1), 'SINT8': ('TIFF_SBYTE', 1),
        'UINT16': ('TIFF_SHORT', 2), 'SINT16': ('TIFF_SSHORT', 2),
        'UINT32': ('TIFF_LONG', 4), 'SINT32': ('TIFF_SLONG', 4),
        'UINT64': ('TIFF_LONG8', 8), 'SINT64': ('TIFF_SLONG8', 8),
        'IFD8': ('TIFF_IFD8', 8), 'FLOAT': ('TIFF_FLOAT', 4),
        'DOUBLE': ('TIFF_DOUBLE', 8), 'ASCII': ('TIFF_ASCII', 1)}
counts = {'TIFF_VARIABLE': 'VARIABLE', 'TIFF_VARIABLE2': 'VARIABLE2', 'TIFF_SPP': 'SPP',
          '-1': 'VARIABLE', '-3': 'VARIABLE2', '-2': 'SPP'}
header = (source / 'tiff.h').read_text()


def tables(path):
    text = re.sub(r'/\*.*?\*/|//[^\n]*', '', path.read_text(), flags=re.S)
    # Retain the standard declarative DNG/EP schemas previously supported here,
    # even where the upstream build disables them with #if 0.
    text = re.sub(r'^\s*#.*$', '', text, flags=re.M)
    result = {}
    for table in re.finditer(r'static const TIFFField\s+(\w+)\[\]\s*=\s*\{(.*?)\};', text, re.S):
        rows = []
        for row in re.finditer(r'\{([^{}]+)\}', table[2], re.S):
            m = re.fullmatch(r'\s*(\w+),\s*(-?\w+),\s*(-?\w+),\s*(TIFF_\w+),\s*0,\s*TIFF_SETGET_(\w+),\s*(\w+),\s*(?:\d|TRUE|FALSE),\s*(\d|TRUE|FALSE),\s*(?:\(char\s*\*\)\s*)?"([^"]*)",\s*(?:\(TIFFFieldArray\s*\*\))?[\w&]+\s*', row[1])
            assert m, (path.name, table[1], row[1])
            tag, rc, wc, typ, get, bit, passc, title = m.groups()
            if bit in ('FIELD_IGNORE', 'FIELD_PSEUDO'):
                continue
            base = re.sub('^C(?:0|16|32)_', '', get)
            # Special get/set shapes are explicitly handled by the adapter.
            # Unknown codec shapes must never silently become anonymous tags.
            assert base in kind or path.name == 'tif_dirinfo.c', (path.name, tag, get)
            host, size = kind.get(base, (typ, 0))
            rows.append({'tag': tag, 'kind': typ, 'read': counts.get(rc, rc),
                         'write': counts.get(wc, wc), 'pass': passc in ('1', 'TRUE'),
                         'size': size,
                         'count_size': 4 if get.startswith('C32_') else 2 if get.startswith('C16_') else 0,
                         'custom': bit == 'FIELD_CUSTOM', 'name': title, 'host': host,
                         'array': get.startswith('C') or base == 'ASCII'})
        assert not re.sub(r'\{[^{}]+\}|[\s,]', '', table[2], flags=re.S), (path, table[1])
        result[table[1]] = rows
    return result


def rust_tag(name):
    prefix, rest = name.split('_', 1)
    return {'TIFFTAG': 'tag::', 'EXIFTAG': 'exif::', 'GPSTAG': 'gps::'}[prefix] + rest


def rust_kind(name):
    return name.removeprefix('TIFF_')


def rust_row(r):
    flag = lambda b: 'true' if b else 'false'
    return (f'    field({rust_tag(r["tag"])}, {rust_kind(r["kind"])}, {r["read"]}, {r["write"]}, '
            f'{flag(r["pass"])}, {r["size"]}, {r["count_size"]}, {flag(r["custom"])}, '
            f'c"{r["name"]}", {rust_kind(r["host"])}, {flag(r["array"])}),')


standard = tables(source / 'tif_dirinfo.c')
codec = {}
for path in sorted(source.glob('tif_*.c')):
    if path.name == 'tif_dirinfo.c':
        continue
    for rows in tables(path).values():
        for r in rows:
            assert r['tag'] not in codec or codec[r['tag']] == r, ('conflicting codec schemas', r['tag'])
            codec[r['tag']] = r
# Pin the full on-file codec inventory, not just the tags a fixture exercises.
assert len(codec) == 15, codec.keys()
assert not set(codec).intersection(r['tag'] for r in standard['tiffFields'])

types = re.findall(r'\bTIFF_(\w+) = (\d+)', re.search(r'typedef enum\s*\{(.*?)\} TIFFDataType;', header, re.S)[1])
schema = ['//! Declarative standard and codec schemas from libtiff 4.7.1.',
          '//! Copyright (c) 1988-1997 Sam Leffler; (c) 1991-1997 Silicon Graphics.',
          '//! See LICENSE-libtiff.md. Generated by generate_fields.py.',
          '//!',
          '//! Each row gives the tag, its registered type, read and write counts,',
          '//! whether a count is passed, the bytes per value and of the count as',
          '//! set and got, whether it is a custom field, its name, the type values',
          '//! are set and got in, and whether they are an array.',
          'use super::fields::{field, Schema, SPP, VARIABLE, VARIABLE2};',
          'use super::tag::{self, exif, gps};',
          'use kind::*;',
          '',
          "/// TIFF data types, named as in tiff.h's TIFFDataType without the TIFF_",
          '/// prefix. `ANY` matches any type in a field search.',
          '#[allow(dead_code)]',
          'pub mod kind {',
          '    pub const ANY: u16 = 0;']
schema += [f'    pub const {name}: u16 = {value};' for name, value in types]
schema += ['}', '']
for name, title in (('tiffFields', 'TIFF'), ('exifFields', 'EXIF'), ('gpsFields', 'GPS')):
    rows = standard[name] + (list(codec.values()) if name == 'tiffFields' else [])
    what = {'TIFF': 'The main directory, with codec fields', 'EXIF': 'EXIF directories',
            'GPS': 'GPS directories'}[title]
    schema += [f'/// {what}.', f'pub static {title}: [Schema; {len(rows)}] = [']
    schema += [rust_row(r) for r in rows]
    schema += ['];', '']

# Name every tag in tiff.h for the adapter, and list the tags the directory
# reader must not read as anonymous.
defines = re.findall(r'#define\s+TIFFTAG_(\w+)\s+(\d+)\b', header)
numbers = {'TIFFTAG_' + name: value for name, value in defines}
known = sorted({int(numbers[r['tag']]) for r in standard['tiffFields']} | {int(numbers[tag]) for tag in codec})
tags = ["//! TIFF tag numbers, named as in libtiff's tiff.h without the TIFFTAG_,",
        '//! EXIFTAG_ or GPSTAG_ prefix, and the tags of libtiff\'s main directory',
        '//! field schemas (schema.rs). Generated by generate_fields.py.',
        '#![allow(dead_code)] // The whole tiff.h table; the adapter uses some of it.',
        '']
tags += [f'pub const {name}: u16 = {value};' for name, value in defines if int(value) <= 0xffff]
tags += ['', "// Pseudo-tags of libtiff's codecs, above the 16-bit tag range."]
tags += [f'pub const {name}: u32 = {value};' for name, value in defines if int(value) > 0xffff]
for module, prefix in (('exif', 'EXIFTAG'), ('gps', 'GPSTAG')):
    tags += ['', f'pub mod {module} {{']
    tags += [f'    pub const {name}: u16 = {value};'
             for name, value in re.findall(rf'#define\s+{prefix}_(\w+)\s+(\d+)\b', header)]
    tags.append('}')
tags += ['', '/// libtiff reads any tag not listed here as an anonymous field.',
         f'pub const KNOWN: [u16; {len(known)}] = [']
tags += ['    ' + ', '.join(map(str, known[i:i + 12])) + ',' for i in range(0, len(known), 12)]
tags.append('];')
p = argparse.ArgumentParser()
p.add_argument('--check', action='store_true')
args = p.parse_args()
for output, text in [(root / 'compat/src/schema.rs', '\n'.join(schema)),
                     (root / 'compat/src/tag.rs', '\n'.join(tags) + '\n')]:
    if args.check:
        assert output.read_text() == text, f'{output.name} is stale; run compat/generate_fields.py'
    else:
        output.write_text(text)
print(f'Field schemas: {len(standard["tiffFields"])} base, {len(codec)} codec, '
      f'{len(standard["exifFields"])} EXIF, {len(standard["gpsFields"])} GPS')
